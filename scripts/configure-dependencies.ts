#!/usr/bin/env node

import * as fs from 'node:fs';
import * as path from 'node:path';

const PLUGIN_ROOT = process.cwd();
const CONFIG_JSON = process.env.CAPACITOR_CONFIG;
const gradlePropertiesPath = path.join(PLUGIN_ROOT, 'android', 'gradle.properties');
const podspecPath = path.join(PLUGIN_ROOT, 'CapgoBackgroundGeolocation.podspec');
const packageSwiftPath = path.join(PLUGIN_ROOT, 'Package.swift');

function readLocationLogSqliteEnabled(): boolean {
  if (!CONFIG_JSON) {
    return false;
  }
  try {
    const config = JSON.parse(CONFIG_JSON);
    const value = config.plugins?.BackgroundGeolocation?.locationLogSqlite;
    if (value === true) {
      return true;
    }
    if (value === false) {
      return false;
    }
    return value === 'implementation';
  } catch {
    return false;
  }
}

function updateGradleProperties(enabled: boolean): void {
  let existingContent = fs.existsSync(gradlePropertiesPath) ? fs.readFileSync(gradlePropertiesPath, 'utf8') : '';
  const lines = existingContent.split('\n').filter((line) => {
    const trimmed = line.trim();
    return (
      !trimmed.startsWith('backgroundGeolocation.locationLogSqlite.') &&
      !trimmed.startsWith('# Background geolocation location log') &&
      trimmed !== '# Generated by BackgroundGeolocation hook script'
    );
  });
  const block = [
    '',
    '# Background geolocation location log (auto-generated by configure-dependencies hook)',
    '# Generated by BackgroundGeolocation hook script',
    `backgroundGeolocation.locationLogSqlite.include=${enabled ? 'true' : 'false'}`,
    `backgroundGeolocation.locationLogSqlite.dependencyType=${enabled ? 'implementation' : 'compileOnly'}`,
    '',
  ];
  fs.writeFileSync(gradlePropertiesPath, lines.join('\n') + block.join('\n'), 'utf8');
}

function updatePodspec(enabled: boolean): void {
  if (!fs.existsSync(podspecPath)) {
    return;
  }
  let content = fs.readFileSync(podspecPath, 'utf8');
  const active =
    "  s.source_files += 'ios/SqliteLocationLog/**/*.swift'\n  s.pod_target_xcconfig = { 'OTHER_SWIFT_FLAGS' => '$(inherited) -DBGGEO_LOCATION_LOG_SQLITE' }";
  const disabled =
    "  # s.source_files += 'ios/SqliteLocationLog/**/*.swift'  # Disabled via config (compileOnly)\n  # s.pod_target_xcconfig = { 'OTHER_SWIFT_FLAGS' => '$(inherited) -DBGGEO_LOCATION_LOG_SQLITE' }  # Disabled via config (compileOnly)";
  const pattern =
    /(#[ \t]*)?s\.source_files \+= 'ios\/SqliteLocationLog\/\*\*\/\*\.swift'.*\n(#[ \t]*)?s\.pod_target_xcconfig = \{ 'OTHER_SWIFT_FLAGS' => '\$\(inherited\) -DBGGEO_LOCATION_LOG_SQLITE' \}.*\n?/;
  if (pattern.test(content)) {
    content = content.replace(pattern, enabled ? active + '\n' : disabled + '\n');
  } else {
    content = content.replace(
      /s\.swift_version = '5\.1'\n/,
      `s.swift_version = '5.1'\n${enabled ? active : disabled}\n`,
    );
  }
  fs.writeFileSync(podspecPath, content, 'utf8');
}

function updatePackageSwift(enabled: boolean): void {
  if (!fs.existsSync(packageSwiftPath)) {
    return;
  }
  let content = fs.readFileSync(packageSwiftPath, 'utf8');
  const sqlitePath = 'ios/SqliteLocationLog';
  const flagLine = enabled
    ? `            swiftSettings: [.define("BGGEO_LOCATION_LOG_SQLITE")],\n            exclude: [],`
    : `            exclude: ["${sqlitePath}"],`;
  if (content.includes('swiftSettings: [.define("BGGEO_LOCATION_LOG_SQLITE")]')) {
    content = content.replace(
      /\s*swiftSettings: \[\.define\("BGGEO_LOCATION_LOG_SQLITE"\)\],\n\s*exclude: \[\],/,
      enabled ? `\n            swiftSettings: [.define("BGGEO_LOCATION_LOG_SQLITE")],\n            exclude: [],` : `\n            exclude: ["${sqlitePath}"],`,
    );
  } else if (content.includes(`exclude: ["${sqlitePath}"]`)) {
    content = content.replace(
      /\s*exclude: \["ios\/SqliteLocationLog"\],/,
      enabled ? `\n            swiftSettings: [.define("BGGEO_LOCATION_LOG_SQLITE")],\n            exclude: [],` : `\n            exclude: ["${sqlitePath}"],`,
    );
  } else {
    content = content.replace(
      /path: "ios\/Sources\/CapgoBackgroundGeolocationPlugin"\),/,
      `path: "ios/Sources/CapgoBackgroundGeolocationPlugin",\n            ${flagLine}`,
    );
  }
  fs.writeFileSync(packageSwiftPath, content, 'utf8');
}

const enabled = readLocationLogSqliteEnabled();
updateGradleProperties(enabled);
updatePodspec(enabled);
updatePackageSwift(enabled);
